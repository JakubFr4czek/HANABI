#!/usr/bin/env python3
"""N9: writes the full credits list from data/credits.json into CREDITS.md and docs/CREDITS_TODO.md.

The same JSON drives the in-game Credits page (Settings > CREDITS), so the menu and
CREDITS.md never disagree (tests/vr_menu_pause_test.gd checks it). Run after editing
data/credits.json:   python3 tools/gen_credits.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- credits:begin (generated by tools/gen_credits.py from data/credits.json; edit the JSON) -->"
END = "<!-- credits:end -->"
UNKNOWN = "autor nieznany"
KIND_TITLE = {"MODEL": "Models", "TEXTURE": "Textures", "SOUND": "Sound effects", "MUSIC": "Music",
              "FONT": "Fonts", "SHADER": "Shaders", "PLUGIN": "Engine and plugins"}


def cell(s: str) -> str:
    return s.replace("|", "\\|")


def main() -> None:
    data = json.loads((ROOT / "data/credits.json").read_text(encoding="utf-8"))
    entries = data["entries"]
    lines = [BEGIN, "## Full list (the same as in game: Settings > CREDITS)", ""]
    for kind, title in KIND_TITLE.items():
        rows = [e for e in entries if e["kind"] == kind]
        if not rows:
            continue
        lines += [f"### {title}", "", "| Name | Author | Source | License | Used for |", "|---|---|---|---|---|"]
        for e in rows:
            lines.append(f"| {cell(e['name'])} | {cell(e['author'])} | {e['source']} | {cell(e['license'])} | {cell(e['use'])} |")
        lines.append("")
    lines += [data.get("closing", ""), END]
    block = "\n".join(lines)

    path = ROOT / "CREDITS.md"
    text = path.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        text = head + block + tail
    else:
        marker = "\n## Assets in the game"
        i = text.find(marker)
        text = (text[:i] + "\n" + block + "\n" + text[i:]) if i >= 0 else (text.rstrip() + "\n\n" + block + "\n")
    path.write_text(text, encoding="utf-8")

    todo = [e for e in entries if e["author"].strip() == "" or UNKNOWN in e["author"]]
    out = ["# Credits TODO", "",
           "Entries of `data/credits.json` whose author is not known from the repo (licence files, LICENSES.md,",
           "CREDITS.md, asset docs). They show \"autor nieznany\" in game and in CREDITS.md until someone checks the source page.", ""]
    if todo:
        out += ["| Name | Source | License | What to check |", "|---|---|---|---|"]
        for e in todo:
            out.append(f"| {cell(e['name'])} | {e['source']} | {cell(e['license'])} | uploader name on the source page |")
    else:
        out.append("Nothing open.")
    (ROOT / "docs/CREDITS_TODO.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"credits: {len(entries)} entries, {len(todo)} without a known author")


if __name__ == "__main__":
    main()
